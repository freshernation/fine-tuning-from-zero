from pathlib import Path

import torch

from tunelab.checkpoint import train_in_chunks
from tunelab.gpt import GPT, count_params
from tunelab.text import CharTokenizer, make_get_batch

# Small enough to train on a laptop CPU in seconds. The tests use this one.
SMALL = dict(block_size=32, n_embd=48, n_head=4, n_layer=2, dropout=0.0)

# The real one. Train it on Colab. It must stay under 2,000,000 parameters.
BIG = dict(block_size=128, n_embd=192, n_head=6, n_layer=4, dropout=0.1)


def run(text, config, steps, path, batch_size=32, lr=3e-3, chunk=500, seed=0, device="cpu"):
    """Train a GPT on `text` with checkpoints at `path`, and report how it went.

    config   SMALL or BIG, above: everything GPT needs except vocab_size
    path     where the checkpoint lives. Call run() again with the same path and
             it carries on from where the last call stopped.
    device   "cpu" or "cuda". The model AND the encoded text both have to move.

    Call torch.manual_seed(seed) first.

    Returns a dict:
        "history"    the whole history, from step 0
        "val_loss"   the last validation loss in it, a float
        "params"     how many parameters the model has, an int
        "sample"     300 characters generated by the trained model, a str
                     (start from a single token with id 0, and do not include it)
    """
    raise NotImplementedError


def count_big_params():
    """How big is the BIG model on a 65-character vocabulary?"""
    return count_params(GPT(vocab_size=65, **BIG))


if __name__ == "__main__":
    text = (Path(__file__).parents[2] / "data" / "tiny.txt").read_text()
    result = run(text, SMALL, steps=500, path="week-02-small.pt")
    for row in result["history"]:
        print(f'step {row["step"]:5d}   train {row["train"]:.3f}   val {row["val"]:.3f}')
    print(f'\n{result["params"]:,} parameters\n')
    print(result["sample"])
